#!/usr/bin/env python3
"""Write the results table in README.md straight from reports/comparison.json.

Every claim in the README about performance is generated, never typed. Running this after
an evaluation is what keeps the prose and the evidence from drifting apart. It also emits
reports/published_numbers.json, which CI compares against a fresh replay run.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPORT = json.loads((ROOT / "reports" / "comparison.json").read_text())

ROWS = [
    ("**Outage misses** (unsafe called safe)", "outage_misses", "lower"),
    ("**Findings backed by tool evidence**", "_grounded", "higher"),
    ("Risk recall", "risk_recall", "higher"),
    ("Risk precision", "risk_precision", "higher"),
    ("Risk F1", "risk_f1", "higher"),
    ("Decision accuracy", "decision_accuracy", "higher"),
    ("False-alarm risks on the 8 safe cases", "false_alarm_risks_on_safe_cases", "lower"),
    ("Total findings reported", "total_findings", ""),
    ("Rewrites offered / validated by execution", "_rewrites", ""),
    ("Model calls", "llm_calls", ""),
    ("Cost for the full 29-case sweep", "_cost", ""),
    ("Harness errors", "errors", "lower"),
]

NAMES = {
    "rules_only": "R0 rules only<br/><sub>no model</sub>",
    "baseline": "B0 baseline<br/><sub>1 call, no tools</sub>",
    "advanced": "**A advanced**<br/><sub>3 agents, live DB</sub>",
}


def cell(system: str, key: str) -> str:
    s = REPORT["systems"][system]["summary"]
    if key == "_grounded":
        total, un = s["total_findings"], s["ungrounded_findings"]
        return f"{total - un} / {total}"
    if key == "_rewrites":
        return f"{s['rewrites_offered']} / {s['rewrites_validated']}" if s["rewrites_offered"] else "—"
    if key == "_cost":
        c = s.get("estimated_cost_usd", 0)
        return "$0.00" if not c else f"${c:.2f}"
    return str(s.get(key, ""))


def main() -> None:
    systems = [s for s in ("rules_only", "baseline", "advanced") if s in REPORT["systems"]]
    lines = [
        f"| Metric | {' | '.join(NAMES[s] for s in systems)} |",
        "|---|" + "---|" * len(systems),
    ]
    for label, key, direction in ROWS:
        arrow = {"higher": " ↑", "lower": " ↓", "": ""}[direction]
        lines.append(f"| {label}{arrow} | " + " | ".join(cell(s, key) for s in systems) + " |")
    table = "\n".join(lines)

    note = (
        f"\n<sub>Model `{REPORT['model']}`, temperature 0, {REPORT['case_count']} cases "
        f"({REPORT['unsafe_cases']} unsafe / {REPORT['safe_cases']} safe), "
        f"{REPORT['seed_rows']} seeded rows per table. Generated by "
        f"`scripts/sync_readme_numbers.py` from `reports/comparison.json` "
        f"({REPORT['generated_at']}); ↑ higher is better, ↓ lower is better. "
        "Only findings graded `medium` or above count as reported risks, applied "
        "identically to every system.</sub>\n"
    )

    readme = ROOT / "README.md"
    text = readme.read_text()
    start, end = "<!-- RESULTS:BEGIN -->", "<!-- RESULTS:END -->"
    a, b = text.index(start) + len(start), text.index(end)
    readme.write_text(text[:a] + "\n" + table + "\n" + note + text[b:])
    print("README results table updated")

    published = {
        s: {
            k: REPORT["systems"][s]["summary"][k]
            for k in ("risk_recall", "risk_precision", "decision_accuracy", "outage_misses",
                      "false_alarm_risks_on_safe_cases", "ungrounded_findings", "rewrites_validated")
        }
        for s in systems
    }
    (ROOT / "reports" / "published_numbers.json").write_text(json.dumps(published, indent=2) + "\n")
    print("wrote reports/published_numbers.json")


if __name__ == "__main__":
    main()
